/**
 * 稳定性契约标注。
 *
 * <p>基线要交给多家银行做二次开发，最常见的失败不是功能不够，而是**行内依赖了不该依赖的东西**：
 * 二开时随手 import 了一个实现类，基线升级把它改了，行内那套跟着崩，然后基线被迫为一个
 * 从没承诺过的类型背兼容责任。久了基线就动不了了。
 *
 * <p>所以要有一条明说的线。这里只有两个正向标注，**没有 {@code @Internal}}**——
 * 默认即内部：
 *
 * <ul>
 *   <li>{@link com.huawei.finance.stability.Api}：行内可以调。签名与语义在大版本内保持兼容。</li>
 *   <li>{@link com.huawei.finance.stability.Spi}：行内可以实现。基线不会往里加抽象方法。</li>
 *   <li>没标的一律是内部实现，随时可改，行内不该依赖。</li>
 * </ul>
 *
 * <p>不设 {@code @Internal} 是有意的。若要靠标注表达「内部」，就得给几百个类逐个加，
 * 而漏标一个的后果是它被**误认为**公开——正好是最危险的方向。反过来「没标就是内部」时，
 * 漏标的后果只是行内不敢用一个本可以用的类型，代价小得多，而且他们会来问。
 *
 * <p>这条线由 {@code com.huawei.finance.arch} 下的 ArchUnit 用例守住，其中最要紧的一条是：
 * {@code @Api} / {@code @Spi} 的公开签名里不许出现没标的类型。承诺了稳定却从签名里
 * 漏出内部类型，那个承诺是兑现不了的——行内为了调用它必然要 import 那个内部类型。
 */
