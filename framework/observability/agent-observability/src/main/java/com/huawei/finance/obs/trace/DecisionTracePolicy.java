package com.huawei.finance.obs.trace;

import com.huawei.finance.stability.Spi;

/**
 * 决策链路记录多少的策略。**这是给使用方覆盖的扩展点。**
 *
 * <p>为什么是扩展点而不是配置项：不同行对 APM 里能出现什么的红线不同。有的行禁止任何
 * 业务关键词进入 APM（证据串里的「余额」「额度」就得摘掉），有的行按渠道分级，
 * 有的行要求候选集只留 top1。这些规则用几个布尔开关表达不完，而写死在基线里
 * 等于让每家行去改我们的代码——那正是基线产品最该避免的事。
 *
 * <p>覆盖方式：在使用方的配置类里声明一个 {@code DecisionTracePolicy} Bean 即可，
 * 基线的默认实现带 {@code @ConditionalOnMissingBean}，会自动让位。
 *
 * <p>实现必须是无状态且线程安全的：每个请求都会调用它，且并发调用。
 */
@Spi
public interface DecisionTracePolicy {

    /**
     * 最多把几条候选写进 span。
     *
     * <p>不是隐私考虑而是成本考虑：候选集常有几十条，每条又是若干属性，全写进去会让
     * 单个 span 膨胀几十倍。APM 后端通常按 span 大小或属性数收费与限流，
     * 超限时的行为是**静默截断整个 span**——那时丢的不只是候选集，是整条链路。
     *
     * <p>返回 0 表示不记候选集。
     */
    int maxCandidates();

    /**
     * 是否把命中证据串写进 span。
     *
     * <p>默认关。证据串里可能有能力卡上的业务关键词（如 {@code keyword:额度}），
     * 它不是用户数据，但足以让人从 APM 反推出行内的产品与规则配置。
     * 打分本身已经够回答「差点选了谁」，证据串是排查规则误命中时才需要的下一层。
     */
    boolean includeEvidence();

    /**
     * 是否记录被负向规则压掉的候选。
     *
     * <p>默认开。这批候选恰恰是排序事故的第一嫌疑人：「明明该选它却没选」多半是
     * 负向规则打压过头，而只记最终 topN 的话，被压到榜外的那条就此消失，
     * 事后无从判断是没召回到还是召回了被压掉——这两种原因的修法完全不同。
     */
    boolean includeSuppressed();
}
